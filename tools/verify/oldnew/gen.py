# Builds Check.kt: the REAL Kotlin of each version, lifted function by function
# out of that version's EasyVoiceTtsService.kt, inside an object of its own
# with the natives replaced by what that version's core answered (probe output).
import re, sys
old_src, new_src, out = sys.argv[1], sys.argv[2], sys.argv[3]
OLD_FNS = ["decodeChunkText", "detectLanguageRuns", "runsFromFlat", "detectedRunsOf",
           "detectLanguageAggregate", "detectLanguage", "foldAndDetect", "isLatinCommonInherited"]
NEW_FNS = ["recordsOf", "detectLanguageRuns", "runsFromFlat", "detectedRunsOf",
           "detectLanguageAggregate", "aggregateOf", "detectWindowThenAggregate", "foldAndDetect",
           "isLatinCommonInherited"]
def lift(src, name):
    text = open(src, encoding="utf-8").read()
    m = re.search(r"^    private fun " + name + r"\(", text, re.M)
    if not m: sys.exit("no function %s in %s" % (name, src))
    i = m.start(); line_end = text.index("\n", i)
    header = text[i:line_end]
    if header.rstrip().endswith("=") or ("=" in header and "{" not in header):
        # expression body: until the first line that closes it at this indent
        j = line_end + 1
        lines = [header]
        depth = header.count("{") - header.count("}")
        while True:
            k = text.index("\n", j); ln = text[j:k]; lines.append(ln); j = k + 1
            depth += ln.count("{") - ln.count("}")
            if depth <= 0 and not ln.rstrip().endswith(("{", "=", ",")): break
        return "\n".join(lines).replace("private fun", "fun")
    depth = 0; j = i
    while True:
        c = text[j]
        if c == "{": depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0: break
        j += 1
    return text[i:j + 1].replace("private fun", "fun")
STUBS = '''
    var quickCharacterFlag = false
    var disableAdvancedFlag = false
    var fold: Array<String> = arrayOf("")
    var window: Array<String> = arrayOf("")
    var full: String = ""
    val log = ArrayList<String>()
    class DetectedRun(val lang: String, val latin: Boolean, val text: String)
    object EasyVoiceLogger {
        const val TAG = "t"
        var sink: ArrayList<String>? = null
        fun isLoggingEnabled() = true
        fun debug(tag: String, m: String) { sink?.add(m) }
        inline fun debug(tag: String, m: () -> String) { sink?.add(m()) }
        fun error(tag: String, m: String) { sink?.add("E " + m) }
    }
    fun initIsoMaps() {}
    fun nativeFoldAndDetect(text: String, q: Boolean): Array<String> = fold
    fun detectLanguageFull(t: String, a: String, b: String, d: Boolean, w: Boolean): String = full
    fun detectWindowOrSpans(t: String, a: String, b: String, d: Boolean, w: Boolean, q: Boolean): Array<String> = window
'''
def obj(name, src, fns):
    return "object %s {\n%s\n%s\n}\n" % (name, STUBS, "\n".join("    " + lift(src, f).strip() for f in fns))
with open(out, "w", encoding="utf-8") as f:
    f.write("// generated by gen.py -- do not edit\n@file:Suppress(\"UNUSED_PARAMETER\", \"UNUSED_VARIABLE\", \"NAME_SHADOWING\")\n")
    f.write(obj("Old", old_src, OLD_FNS))
    f.write(obj("New", new_src, NEW_FNS))
    # the app's generated Unicode table (2026-10-06), beside the new service
    import os
    ut = os.path.join(os.path.dirname(new_src), "UnicodeTables.kt")
    if os.path.exists(ut):
        f.write(open(ut, encoding="utf-8").read().split("\n", 1)[1].replace("internal object", "object") + "\n")
    f.write(open(sys.argv[4], encoding="utf-8").read())
