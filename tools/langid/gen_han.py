#!/usr/bin/env python3
"""The Han character sets the detector's Chinese/Japanese rules read.

    gen_han.py --extract Unihan_IRGSources.txt   rewrite tools/langid/han_sets.txt
    gen_han.py                                   write app/src/main/cpp/langhan.h
    gen_han.py --check                           fail if langhan.h is stale

han_sets.txt holds, for every Han character in at least one of them, which of
three national character sets has it (Unihan 18.0.0's IRG sources):
  S  kIRG_GSource G0      GB 2312, the characters of Simplified Chinese
  T  kIRG_TSource T1, T2  CNS 11643 planes 1 and 2, Traditional Chinese
  J  kIRG_JSource J0      JIS X 0208, the kanji of everyday Japanese
All of them lie in U+4E00..U+9FFF, so the header is three bitsets over that
block. Unihan.zip comes from https://www.unicode.org/Public/18.0.0/ucd/
(tools/verify/langsuite/fetch_data.sh fetches it); Unicode License v3.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SETS = os.path.join(ROOT, "tools", "langid", "han_sets.txt")
OUT = os.path.join(ROOT, "app", "src", "main", "cpp", "langhan.h")
FIRST, LAST = 0x4E00, 0x9FFF
HEADER = """# Han characters by the character sets that hold them, from Unihan 18.0.0
# (https://www.unicode.org/Public/18.0.0/ucd/Unihan.zip, Unihan_IRGSources.txt,
# Unicode License v3): S = kIRG_GSource G0 (GB 2312, Simplified Chinese),
# T = kIRG_TSource T1 or T2 (CNS 11643 planes 1-2, Traditional Chinese),
# J = kIRG_JSource J0 (JIS X 0208, the kanji of everyday Japanese).
# Written by tools/langid/gen_han.py --extract; do not edit.
"""


def extract(path):
    want = {("kIRG_GSource", "G0"): "S", ("kIRG_TSource", "T1"): "T", ("kIRG_TSource", "T2"): "T",
            ("kIRG_JSource", "J0"): "J"}
    sets = {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        cp, field, val = line.rstrip("\n").split("\t")
        tag = want.get((field, val.split("-")[0]))
        if tag:
            sets.setdefault(int(cp[2:], 16), set()).add(tag)
    with open(SETS, "w", encoding="utf-8") as f:
        f.write(HEADER)
        for cp in sorted(sets):
            f.write("U+%04X\t%s\n" % (cp, "".join(sorted(sets[cp]))))
    print("han_sets.txt: %d characters" % len(sets))


def header():
    bits = {k: bytearray((LAST - FIRST + 1 + 7) // 8) for k in "STJ"}
    for line in open(SETS, encoding="utf-8"):
        if line.startswith("#"):
            continue
        cp, tags = line.split()
        cp = int(cp[2:], 16)
        assert FIRST <= cp <= LAST, hex(cp)
        for t in tags:
            bits[t][(cp - FIRST) >> 3] |= 1 << ((cp - FIRST) & 7)
    out = ["// Generated by tools/langid/gen_han.py from tools/langid/han_sets.txt (Unihan",
           "// 18.0.0 IRG sources) -- do not edit. Bit (cp - 0x4E00) of each set.",
           "#pragma once",
           "#include <cstdint>",
           "static const int32_t kHanFirst = 0x%04X, kHanLast = 0x%04X;" % (FIRST, LAST)]
    names = {"S": "kHanSimplified  // GB 2312", "T": "kHanTraditional  // CNS 11643 planes 1-2",
             "J": "kHanJapanese  // JIS X 0208"}
    for t in "STJ":
        name, note = names[t].split("  ")
        out.append("static const uint8_t %s[%d] = {  %s" % (name, len(bits[t]), note))
        for i in range(0, len(bits[t]), 24):
            out.append("    " + ",".join("%d" % b for b in bits[t][i:i + 24]) + ",")
        out.append("};")
    out.append("static inline bool hanIn(const uint8_t* set, int32_t cp) {")
    out.append("    return cp >= kHanFirst && cp <= kHanLast && (set[(cp - kHanFirst) >> 3] >> ((cp - kHanFirst) & 7) & 1);")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--extract":
        extract(sys.argv[2])
    elif len(sys.argv) == 2 and sys.argv[1] == "--check":
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != header():
            print("langhan.h is stale: run tools/langid/gen_han.py")
            sys.exit(1)
        print("langhan.h current")
    else:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(header())
        print("wrote", OUT)
